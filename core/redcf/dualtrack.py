# -*- coding: utf-8 -*-
"""
core/redcf/dualtrack.py — 雙軌財務口徑（私約軌 vs 公法軌）
============================================================================
**領域來源**：一件在途真實案（案例E，防災都更2.0＋權變；本機 /local_calibration/）指出——
同一個案子存在**兩套皆為真實**的數字，服務不同對象、依據不同基準：

  私約軌（開發報酬視角）  以**實際發包造價**＋全案銷售 → 全案報酬率
                          回答：「這塊地自建自售，扣真實成本後能賺多少」
  公法軌（法定分配視角）  以**法定造價標準／§51 提列基準** → 共同負擔比
                          回答：「地主依法須以更新後分回，折價抵付實施者多少比例」

**它們不是同一個量的兩個值，而是兩個不同對象各自的關鍵指標** —— 把報酬率（利潤÷成本）
與負擔比（共同負擔÷更新後總權利價值）直接相比是常見誤讀。

兩軌之隱含共負比仍有差距，差距來自「實際造價 vs 法定造價標準」與各費目提列口徑。
**本模組把該差距明確歸因並附殘差**，保證：

    造價基準差 + 其他提列口徑差(residual) = 公法軌共負比 − 私約軌隱含共負比

（與 attribution 的「加總守恆」同一紀律：數字必須對得起來，否則解釋沒有價值。）

**SSOT**：本模組**零新公式**——兩軌皆呼叫既有 `calc_投報全案`，只是餵不同的造價基準。
"""
from core.redcf.finance import calc_投報全案

__all__ = ["calc_雙軌口徑", "calc_三種報酬率"]


def calc_雙軌口徑(銷售坪數, 營造樓地板坪, p: dict, 模式: str = "全案管理",
                  法定造價單價: float = None) -> dict:
    """回傳私約軌／公法軌兩組結果與差距歸因（單位：萬元）。

    p["營造單價"]＝**實際發包造價**（私約軌基準）。
    法定造價單價＝**法定造價標準**（公法軌基準）；None＝兩軌同基準（差距僅來自提列口徑）。
    """
    私 = calc_投報全案(銷售坪數, 營造樓地板坪, p, 模式)

    if 法定造價單價 is None:
        公 = 私
    else:
        p公 = dict(p)
        p公["營造單價"] = 法定造價單價
        公 = calc_投報全案(銷售坪數, 營造樓地板坪, p公, 模式)

    私共負比, 公共負比 = 私["共負比"], 公["共負比"]
    總差 = 公共負比 - 私共負比

    # 歸因：只改造價基準（其餘輸入固定）造成的差 ＝ 造價基準差；其餘歸 residual。
    造價基準差 = 總差 if 法定造價單價 is not None else 0.0
    residual = 總差 - 造價基準差          # 守恆：兩者相加恆等於總差

    return {
        "私約軌": {
            "_定義": "實際發包造價＋全案銷售；回答『自建自售能賺多少』",
            "基準": "實際發包造價", "營造單價": p.get("營造單價"),
            "總銷": 私["總銷"], "共同負擔": 私["共同負擔"],
            "隱含共負比": round(私共負比, 6),
            "全案報酬率": round(私["報酬率"], 6),
            "地主分回比": round(私["地主分回比"], 6),
        },
        "公法軌": {
            "_定義": "法定造價標準／§51 逐項提列；回答『地主須折價抵付多少』",
            "基準": "法定造價標準" if 法定造價單價 is not None else "同私約軌（未給法定基準）",
            "營造單價": 法定造價單價 if 法定造價單價 is not None else p.get("營造單價"),
            "總銷": 公["總銷"], "共同負擔": 公["共同負擔"],
            "共同負擔比": round(公共負比, 6),
            "地主分回比": round(公["地主分回比"], 6),
            "科目": {k: 公[k] for k in ("A工程費用", "B管維費用", "C權變費用",
                                        "D貸款利息", "E稅捐", "F管理費用", "G土地成本")},
        },
        "差距歸因": {
            "_note": "造價基準差 ＋ 其他提列口徑差(residual) ＝ 總差（守恆）",
            "總差": round(總差, 6),
            "造價基準差": round(造價基準差, 6),
            "其他提列口徑差_residual": round(residual, 6),
        },
        "_不可直接比": ("全案報酬率＝利潤÷成本；共同負擔比＝共同負擔÷更新後總權利價值。"
                        "兩者分屬不同維度、不同對象，不得直接比較大小。"),
        "模式": 模式,
    }


def calc_三種報酬率(銷售坪數, 營造樓地板坪, p: dict, 模式: str = "全案管理",
                    權變戶比例: float = None, 自籌成數: float = None,
                    後付款項: float = 0.0, 權變戶分回價值: float = None) -> dict:
    """同一案的三種報酬率並存（實務上最常被混談的三個數字）。

    權變戶比例＝權變戶占全案之比重（None＝不拆算）。
    權變戶分回價值＝§56 權利變換之權變戶分回總值（缺則該率標 insufficient_data，不臆造）。
    自籌成數＝自有資金占總成本比（None＝取 1 − 建融成數）。
    後付款項＝營造保留款／稅金／管理費等後付金額；用於「付款時程情境」——
        真實案顯示：同一案僅因付款時程設計不同，自有資金報酬率可由正翻負。
    """
    inv = calc_投報全案(銷售坪數, 營造樓地板坪, p, 模式)
    總成本 = inv["共同負擔"]
    利潤 = inv["總銷"] - 總成本

    out = {
        "全案報酬率": {"值": round(inv["報酬率"], 6),
                       "定義": "全案利潤 ÷ 全案總成本", "視角": "自建自售（含全部戶數）"},
        "_note": "三者分母不同，不可互相取代；引用時務必標明是哪一種。",
    }

    if 權變戶比例 is not None:
        r = max(0.0, min(1.0, 權變戶比例))
        權成本 = 總成本 * r
        if 權變戶分回價值 is None:
            # ⚠️ 不得以等比例切分推導：權變戶取得房屋走§56分回、非市價購買，
            # 收入結構與銷售戶不同；等比例切分會恆等於全案報酬率＝假數字。
            out["全案權變報酬率"] = {
                "值": None, "status": "insufficient_data",
                "定義": "權變戶利潤 ÷ 權變戶成本", "視角": "僅計權變戶部分",
                "_why": ("需提供『權變戶分回價值』（來自 rights.calc_權利變換 §56）。"
                         "不可由全案利潤等比例切分——那會恆等於全案報酬率，是無意義的數字。")}
        else:
            權利潤 = 權變戶分回價值 - 權成本
            out["全案權變報酬率"] = {
                "值": round(權利潤 / 權成本, 6) if 權成本 else None,
                "定義": "權變戶利潤 ÷ 權變戶成本", "視角": "僅計權變戶部分",
                "權變戶比例": r, "權變戶分回價值": 權變戶分回價值,
                "_note": "分回價值來自 §56 權利變換，非市價銷售——故本率通常遠低於全案報酬率。"}

    成數 = 自籌成數 if 自籌成數 is not None else max(0.0, 1.0 - p.get("建融成數", 0.0))
    自籌 = 總成本 * 成數
    if 自籌:
        out["自有資金報酬率"] = {
            "值": round(利潤 / 自籌, 6),
            "定義": "利潤 ÷ 自籌款", "視角": f"財務槓桿放大後（自籌成數 {成數:.0%}）"}
        if 後付款項:
            out["情境_後付款項全計入"] = {
                "值": round((利潤 - 後付款項) / 自籌, 6),
                "定義": "後付款項全數計入後之自有資金報酬",
                "視角": "營造保留款／稅金／管理費後付時",
                "後付款項": 後付款項,
                "_warning": "付款時程設計可使本項由正翻負——開發報酬對付款結構高度敏感。"}
    return out
