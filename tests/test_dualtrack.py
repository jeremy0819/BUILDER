# -*- coding: utf-8 -*-
"""tests/test_dualtrack.py — 雙軌財務口徑（私約軌 vs 公法軌）。

領域來源：一件在途真實案（案例E）指出同案存在兩套皆真實的數字。
本檔鎖住的領域真理：
  1. 兩軌是**不同維度**（報酬率 vs 負擔比），不可直接比大小。
  2. 差距歸因必須**加總守恆**（造價基準差 ＋ residual ＝ 總差）。
  3. 法定造價高於實際造價時，公法軌共負比必**高於**私約軌隱含共負比。
  4. 權變報酬率**不得**由全案利潤等比例切分（那會恆等於全案報酬率＝假數字）。
  5. 付款時程可使自有資金報酬率顯著下降（真實案顯示可由正翻負）。
零真實資料：參數為合成。"""
import pytest
from core.redcf import calc_雙軌口徑, calc_三種報酬率, 財務率預設


def _p(營造單價=22):
    p = dict(財務率預設)
    p.update({"住宅單價": 78, "店舖坪數": 60, "店舖單價": 120, "車位數": 40,
              "車位單價": 230, "營造單價": 營造單價, "戶數": 112, "權變戶數": 60,
              "土地成本": 0})
    return p


# ── 雙軌 ──

def test_差距歸因_加總守恆():
    """造價基準差 ＋ residual ＝ 總差（與 attribution 同一紀律：數字必須對得起來）。"""
    d = calc_雙軌口徑(2400, 4200, _p(22), "全案管理", 法定造價單價=26)
    g = d["差距歸因"]
    assert abs(g["造價基準差"] + g["其他提列口徑差_residual"] - g["總差"]) < 1e-9


def test_法定造價較高時_公法軌共負比較高():
    d = calc_雙軌口徑(2400, 4200, _p(22), "全案管理", 法定造價單價=26)
    assert d["公法軌"]["共同負擔比"] > d["私約軌"]["隱含共負比"]
    assert d["差距歸因"]["總差"] > 0


def test_未給法定基準時_兩軌同值且總差為零():
    d = calc_雙軌口徑(2400, 4200, _p(22), "全案管理")
    assert d["差距歸因"]["總差"] == 0.0
    assert d["公法軌"]["共同負擔比"] == d["私約軌"]["隱含共負比"]


def test_兩軌是不同維度_必須明示不可直接比():
    d = calc_雙軌口徑(2400, 4200, _p(22), "全案管理", 法定造價單價=26)
    assert "不得直接比較" in d["_不可直接比"]
    # 報酬率與負擔比是不同量：兩者同時存在且各有定義
    assert "報酬率" in d["私約軌"]["_定義"] or "賺多少" in d["私約軌"]["_定義"]
    assert "折價抵付" in d["公法軌"]["_定義"]


def test_公法軌逐項科目齊備():
    d = calc_雙軌口徑(2400, 4200, _p(22), "全案管理", 法定造價單價=26)
    for k in ("A工程費用", "B管維費用", "C權變費用", "D貸款利息", "E稅捐", "F管理費用"):
        assert k in d["公法軌"]["科目"]


# ── 三種報酬率 ──

def test_權變報酬率_缺分回價值時標insufficient_不臆造():
    """★ 不得以等比例切分推導——那會恆等於全案報酬率，是無意義的假數字。"""
    r = calc_三種報酬率(2400, 4200, _p(), "全案管理", 權變戶比例=0.54)
    w = r["全案權變報酬率"]
    assert w["值"] is None and w["status"] == "insufficient_data"
    assert "等比例切分" in w["_why"]


def test_權變報酬率_有分回價值時與全案報酬率不同():
    r = calc_三種報酬率(2400, 4200, _p(), "全案管理",
                       權變戶比例=0.54, 權變戶分回價值=95000)
    assert r["全案權變報酬率"]["值"] is not None
    assert r["全案權變報酬率"]["值"] != r["全案報酬率"]["值"]


def test_三種報酬率分母不同_不可互相取代():
    r = calc_三種報酬率(2400, 4200, _p(), "全案管理")
    assert "不可互相取代" in r["_note"]
    # 自有資金報酬率因槓桿放大，必高於全案報酬率
    assert r["自有資金報酬率"]["值"] > r["全案報酬率"]["值"]


def test_付款時程_後付款項使自有資金報酬下降():
    """真實案顯示：同一案僅因付款時程設計不同，自有資金報酬率可由正翻負。"""
    base = calc_三種報酬率(2400, 4200, _p(), "全案管理")
    後付 = calc_三種報酬率(2400, 4200, _p(), "全案管理", 後付款項=12000)
    assert 後付["情境_後付款項全計入"]["值"] < base["自有資金報酬率"]["值"]
    assert "正翻負" in 後付["情境_後付款項全計入"]["_warning"]


def test_後付款項極大時可翻為負():
    inv_like = calc_三種報酬率(2400, 4200, _p(), "全案管理")
    大額 = calc_三種報酬率(2400, 4200, _p(), "全案管理", 後付款項=400000)
    assert 大額["情境_後付款項全計入"]["值"] < 0 < inv_like["自有資金報酬率"]["值"]


# ── SSOT：本模組零新公式 ──

def test_零新公式_兩軌皆委派既有Core():
    """雙軌不得自行實作財務公式：私約軌結果須與直接呼叫 calc_投報全案 完全一致。"""
    from core.redcf import calc_投報全案
    p = _p(22)
    ref = calc_投報全案(2400, 4200, p, "全案管理")
    d = calc_雙軌口徑(2400, 4200, p, "全案管理", 法定造價單價=26)
    assert d["私約軌"]["總銷"] == ref["總銷"]
    assert d["私約軌"]["共同負擔"] == ref["共同負擔"]
    assert abs(d["私約軌"]["全案報酬率"] - round(ref["報酬率"], 6)) < 1e-9
